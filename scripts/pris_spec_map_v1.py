def classify(unit):
    """unit dict(type, model, name) → (spec dict, 근거)"""
    t = (unit.get("type") or "").strip()
    model = (unit.get("model") or "").strip()
    name = (unit.get("name") or "").strip().upper()

    base = dict(TYPE_SPECS.get(t) or TYPE_SPECS["X"])
    basis = f"타입 기본값({t})" if t in TYPE_SPECS else "미분류"
    notes = [base.get("스펙_비고", "")]

    for pat, ov in MODEL_RULES:
        if model and re.search(pat, model, re.I):
            for k, v in ov.items():
                if k == "스펙_비고":
                    notes.append(v)
                else:
                    base[k] = v
            basis = f"모델 규칙({model})"
            break

    for pat, ov in NAME_RULES:
        if re.search(pat, name):
            for k, v in ov.items():
                if k == "스펙_비고":
                    notes.append(v)
                else:
                    base[k] = v
            basis += " + 유닛 특례"
            break

    base["스펙_비고"] = "; ".join([n for n in notes if n])
    return base, basis
